import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { AstronautId } from '@orbital/contracts';
import { initialState, respond, type CompanionContext } from '@orbital/companion';
import { buildIntelligenceReport, evaluate, extractDailyFeatures, mlAdvisoryBlock, trainModel } from '@orbital/engine';
import { dailyMissions, evaluateProgress, simulationEvents } from '@orbital/gamification';
import { FORBIDDEN_WORDING, recommend } from '@orbital/recommendations';
import { allSignals } from '@orbital/signals';
import { CREW, SCENARIO_TRUTH, generateMission, generateVirtualMission, trainingCohortSpecs } from '@orbital/simulation';

/**
 * Part D — demonstration scenarios (SYNTHETIC data; no clinical validation claimed).
 * For each of the five crew members the full chain runs:
 *   statistics → ML advisory → deterministic decision → recommendation → companion line → mission reward.
 * Set ORBITAL_WRITE_DEMO=1 to regenerate docs/phase-4-demonstration-scenarios.results.json.
 */

const signals = allSignals();
const model = trainModel(trainingCohortSpecs().map((s) => ({ seed: s.seed, records: generateVirtualMission(s).records })), signals);
const DEMO: { id: AstronautId; day: number }[] = [
  { id: 'CM-01', day: 150 },
  { id: 'CM-02', day: 100 },
  { id: 'CM-03', day: 150 },
  { id: 'CM-04', day: 130 },
  { id: 'CM-05', day: 120 },
];
const voice = { name: 'Mochi', interjections: ['Mew!'], happyAction: 'do a happy ear-wiggle', signoff: '♡' };

function run(id: AstronautId, day: number) {
  const records = generateMission(id).records;
  const assessment = evaluate({ records, signals, asOfDay: day, safety: [] });
  const report = buildIntelligenceReport({ subjectId: id, records, signals, asOfDay: day }, assessment, mlAdvisoryBlock(model, extractDailyFeatures(records, signals), day));
  const recs = recommend(report.approved, { restDay: day % 7 === 6 });
  const ctx: CompanionContext = {
    firstName: CREW[id].profile.name.split(' ')[0]!, timeOfDay: 'morning', restDay: false, sleepBelowUsual: false, activityBelowUsual: false, measurementDue: false,
    exerciseDoneToday: false, achievementsToday: [], alertActive: false, journalingEnabled: true, journalDoneToday: false, suggestions: recs.recommendations.map((r) => r.title),
  };
  const pet = respond(initialState(), { action: 'open' }, ctx, voice, 0, 1);
  const missions = dailyMissions(day, { restDay: false, sleepBelowUsual: false, activityBelowUsual: false, measurementDay: false, recommendations: recs.recommendations }, []);
  const adaptive = missions.find((m) => m.adaptive) ?? null;
  // Reward: complete the adaptive mission's first counted activity and compare XP with/without it.
  const events = simulationEvents(id, records).filter((e) => e.missionDay <= day);
  const opts = { prescribedExerciseMin: CREW[id].baselines.resistMin + CREW[id].baselines.aerobicMin, contextForDay: (d: number) => ({ restDay: d % 7 === 6, sleepBelowUsual: false, activityBelowUsual: false, measurementDay: false, recommendations: d === day ? recs.recommendations : [] }) };
  const xpBefore = evaluateProgress(id, events, day, opts).xp;
  const done = adaptive ? [...events, { id: `demo:${id}`, subjectId: id, missionDay: day, kind: adaptive.counts[0]!, amount: adaptive.counts[0] === 'exercise.session' ? 30 : 1, source: 'user' as const }] : events;
  const xpAfter = evaluateProgress(id, done, day, opts).xp;
  return { id, day, scenario: CREW[id].profile.scenarioLabel, onset: SCENARIO_TRUTH[CREW[id].profile.scenario].onsetDay, assessment, report, recs, pet, adaptive, xpGain: xpAfter - xpBefore };
}

const results = DEMO.map((d) => run(d.id, d.day));
const by = (id: string) => results.find((r) => r.id === id)!;

if (process.env['ORBITAL_WRITE_DEMO'] === '1') {
  writeFileSync(
    new URL('../docs/phase-4-demonstration-scenarios.results.json', import.meta.url),
    JSON.stringify(
      {
        note: 'SYNTHETIC demonstration — generated by tests/phase4-demo.test.ts (ORBITAL_WRITE_DEMO=1). Not clinically validated.',
        modelHash: model.hash,
        scenarios: results.map((r) => ({
          astronaut: r.id,
          scenario: r.scenario,
          day: r.day,
          groundTruthOnsetDay: r.onset,
          statistical: r.report.statistical.map((f) => ({ kind: f.kind, signal: f.signalId, method: f.method, sinceDay: f.sinceDay ?? null })),
          ml: { status: r.report.ml.status, score: r.report.ml.score, threshold: r.report.ml.threshold, daysAbove: r.report.ml.daysAboveThreshold, topFeatures: r.report.ml.topFeatures },
          decision: { state: r.assessment.state, rules: r.assessment.trace.rulesFired, reason: r.assessment.reasons.find((x) => x.tier === 'DECISION' || x.tier === 'SUFFICIENCY')?.text ?? null },
          approved: r.report.approved,
          recommendations: r.recs.recommendations.map((x) => ({ kind: x.kind, title: x.title, basis: x.basis.source })),
          companion: r.pet.reply,
          adaptiveMission: r.adaptive ? { title: r.adaptive.title, bonusXp: r.adaptive.bonusXp, completedBy: r.adaptive.counts } : null,
          xpForCompletingIt: r.xpGain,
          nasaRisks: r.report.nasaRiskIds,
        })),
      },
      null,
      2,
    ) + '\n',
  );
}

describe('Part D demonstration scenarios (synthetic)', () => {
  it('healthy adaptation: nothing detected, no adaptive mission, routine missions only', () => {
    const r = by('CM-01');
    expect(r.assessment.state).toBe('NO');
    expect(r.report.ml.status).toBe('no-alarm');
    expect(r.recs.recommendations).toEqual([]);
    expect(r.adaptive).toBeNull();
  });

  it('sleep disruption: sustained sleep change → recovery expedition, relayed by the pet, rewarded for completion', () => {
    const r = by('CM-02');
    expect(r.report.approved.sustainedDomains).toContain('sleep');
    expect(r.recs.recommendations[0]!.kind).toBe('sleep-recovery-expedition');
    expect(r.pet.reply).toContain('Recovery expedition');
    expect(r.xpGain).toBeGreaterThan(0);
  });

  it('physical deconditioning: trend detected, decision stays NO, movement mission offered', () => {
    const r = by('CM-03');
    expect(r.assessment.state).toBe('NO');
    expect(r.report.approved.physicalTrendSignals.length).toBeGreaterThan(0);
    expect(r.recs.recommendations.map((x) => x.kind)).toContain('movement-short');
  });

  it('wellbeing changes: YES decision → voluntary journal first; the pet never mentions a diagnosis', () => {
    const r = by('CM-04');
    expect(r.assessment.state).toBe('YES');
    expect(r.recs.recommendations[0]!.kind).toBe('journal');
    expect(r.pet.reply).not.toMatch(/depress|diagnos|disorder/i);
  });

  it('incomplete telemetry: INSUFFICIENT DATA, ML withheld, only a gentle measurement reminder', () => {
    const r = by('CM-05');
    expect(r.assessment.state).toBe('INSUFFICIENT_DATA');
    expect(r.report.ml.status).toBe('withheld');
    expect(r.recs.recommendations.map((x) => x.kind)).toEqual(['measurement-reminder']);
  });

  it('every pet line relays an approved title verbatim (or a greeting) and is never LLM-eligible when it carries a suggestion', () => {
    for (const r of results) {
      if (r.recs.recommendations.length) {
        expect(r.pet.reply).toContain(r.recs.recommendations[0]!.title);
        expect(r.pet.llmEligible).toBe(false);
      }
      expect(r.pet.reply).not.toMatch(FORBIDDEN_WORDING);
    }
  });

  it('the companion lists all approved ideas on request and says so when there are none', () => {
    const r = by('CM-03');
    const ctx = { firstName: 'X', timeOfDay: 'morning', restDay: false, sleepBelowUsual: false, activityBelowUsual: false, measurementDue: false, exerciseDoneToday: false, achievementsToday: [], alertActive: false, journalingEnabled: true, journalDoneToday: false } as CompanionContext;
    const list = respond(initialState(), { text: 'what should I do today?' }, { ...ctx, suggestions: r.recs.recommendations.map((x) => x.title) }, voice, 0, 3);
    for (const x of r.recs.recommendations) expect(list.reply).toContain(x.title);
    expect(respond(initialState(), { text: 'any ideas?' }, { ...ctx, suggestions: [] }, voice, 0, 3).reply).toMatch(/Nothing special|No extra ideas/);
  });
});
