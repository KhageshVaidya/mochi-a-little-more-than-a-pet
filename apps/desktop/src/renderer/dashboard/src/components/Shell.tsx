import type { ReactNode } from 'react';
import {
  Activity,
  Brain,
  BookOpen,
  FileText,
  FlaskConical,
  HeartPulse,
  LayoutGrid,
  Library,
  Pause,
  Play,
  RotateCcw,
  Settings2,
  Sparkles,
  Trophy,
  Users,
  type LucideIcon,
} from 'lucide-react';
import { MISSION_LENGTH_DAYS, PLAYBACK_SPEEDS, type AstronautId } from '@orbital/contracts';
import { useApp, type SectionId } from '../stores/app';
import { cn, metLabel } from '../lib/cn';
import { OrbitalMark } from './OrbitalMark';
import { SegmentedControl } from './ui';
import { CrewSwitcher } from './crew';

export const NAV: { id: SectionId; label: string; icon: LucideIcon }[] = [
  { id: 'overview', label: 'Overview', icon: LayoutGrid },
  { id: 'crew', label: 'Crew', icon: Users },
  { id: 'physical', label: 'Physical Health', icon: HeartPulse },
  { id: 'brain', label: 'Brain & Mental Health', icon: Brain },
  { id: 'journal', label: 'Journal & Memory', icon: BookOpen },
  { id: 'telemetry', label: 'Live Telemetry', icon: Activity },
  { id: 'challenges', label: 'Mission Challenges', icon: Trophy },
  { id: 'reports', label: 'Health Reports', icon: FileText },
  { id: 'knowledge', label: 'NASA Research & Risk Knowledge', icon: Library },
  { id: 'companion', label: 'Desktop Companion', icon: Sparkles },
  { id: 'settings', label: 'Settings', icon: Settings2 },
];


function Sidebar() {
  const { section, navigate } = useApp();
  return (
    <aside className="no-print drag flex w-[240px] shrink-0 flex-col border-r border-line bg-sidebar">
      {/* Space for macOS traffic lights */}
      <div className="h-[52px] shrink-0" />
      <div className="flex items-center gap-2.5 px-5 pb-6">
        <OrbitalMark />
        <span className="font-display text-[15px] font-semibold tracking-[0.14em] text-ink">DR G ZERO</span>
      </div>
      <nav className="no-drag flex flex-col gap-0.5 px-3" aria-label="Sections">
        {NAV.map(({ id, label, icon: Icon }) => {
          const active = section === id;
          return (
            <button
              key={id}
              onClick={() => navigate(id)}
              aria-current={active ? 'page' : undefined}
              className={cn(
                't-footnote flex h-9 items-center gap-3 rounded-[10px] px-3 text-left font-medium transition-colors duration-150',
                active ? 'bg-surface text-ink shadow-card' : 'text-ink-2 hover:bg-surface-2/70 hover:text-ink',
              )}
            >
              <Icon size={17} strokeWidth={1.75} className={active ? 'text-accent' : 'text-ink-3'} />
              {label}
            </button>
          );
        })}
      </nav>
      <div className="mt-auto px-4 pb-4">
        <CrewSwitcher />
      </div>
    </aside>
  );
}

function TitleBar() {
  const mission = useApp((s) => s.mission);
  const section = useApp((s) => s.section);
  const title = NAV.find((n) => n.id === section)?.label ?? (section === 'setup' ? 'Set up local AI' : undefined);
  return (
    <div className="no-print drag flex h-[52px] shrink-0 items-center justify-between border-b border-line px-8">
      <span className="t-footnote font-medium text-ink-3">{title}</span>
      <div className="flex items-center gap-3">
        {mission && <span className="t-footnote tabular font-mono text-ink-2">{metLabel(mission.day)}</span>}
        <span
          className="t-caption inline-flex items-center gap-1.5 rounded-full bg-synthetic-soft px-2.5 py-1 font-semibold text-synthetic"
          title="All physiological and wellbeing values in this build are generated by the synthetic simulation engine."
        >
          <FlaskConical size={13} strokeWidth={2} />
          SIMULATED DATA
        </span>
      </div>
    </div>
  );
}

function MissionBar() {
  const { mission, missionCommand, crew } = useApp();
  if (!mission) return <div className="h-[60px] border-t border-line" />;
  const fill = `${(mission.day / (MISSION_LENGTH_DAYS - 1)) * 100}%`;
  return (
    <footer className="no-print flex h-[60px] shrink-0 items-center gap-5 border-t border-line bg-surface/70 px-8 backdrop-blur">
      <div className="flex items-center gap-1">
        <button
          aria-label={mission.playing ? 'Pause playback' : 'Play mission'}
          onClick={() => missionCommand({ type: mission.playing ? 'pause' : 'play' })}
          className="flex h-8 w-8 items-center justify-center rounded-full bg-accent text-bg transition-transform active:scale-95"
        >
          {mission.playing ? <Pause size={14} fill="currentColor" /> : <Play size={14} fill="currentColor" className="ml-0.5" />}
        </button>
        <button
          aria-label="Reset mission to day 0"
          onClick={() => missionCommand({ type: 'reset' })}
          className="flex h-8 w-8 items-center justify-center rounded-full text-ink-2 hover:bg-surface-2 hover:text-ink"
        >
          <RotateCcw size={15} strokeWidth={1.75} />
        </button>
      </div>
      <div className="flex min-w-0 flex-1 items-center gap-4">
        <span className="t-footnote tabular w-[104px] shrink-0 font-medium text-ink">
          Day {mission.day} <span className="text-ink-3">/ {MISSION_LENGTH_DAYS}</span>
        </span>
        <input
          type="range"
          aria-label="Mission day"
          className="o-range min-w-0 flex-1"
          style={{ ['--o-fill' as string]: fill }}
          min={0}
          max={MISSION_LENGTH_DAYS - 1}
          value={mission.day}
          onChange={(e) => missionCommand({ type: 'seek', day: Number(e.target.value) })}
        />
      </div>
      <SegmentedControl
        size="sm"
        label="Playback speed (mission-days per minute)"
        value={mission.speed}
        options={PLAYBACK_SPEEDS.map((s) => ({ value: s, label: `${s}×`, title: `${s} mission-days per minute` }))}
        onChange={(speed) => missionCommand({ type: 'speed', speed })}
      />
      <select
        aria-label="Scenario (crew member)"
        title="Each fictional crew member follows one simulation scenario"
        value={mission.astronautId}
        onChange={(e) => missionCommand({ type: 'select', astronautId: e.target.value as AstronautId })}
        className="t-footnote h-8 max-w-[260px] rounded-[10px] border border-line bg-surface px-2.5 font-medium text-ink outline-none"
      >
        {crew.map((c) => (
          <option key={c.id} value={c.id}>
            {c.scenarioLabel} — {c.name}
          </option>
        ))}
      </select>
    </footer>
  );
}

export function Shell({ children }: { children: ReactNode }) {
  return (
    <div className="print-root flex h-full">
      <Sidebar />
      <div className="flex min-w-0 flex-1 flex-col">
        <TitleBar />
        <main className="print-main min-h-0 flex-1 overflow-y-auto">
          <div className="mx-auto max-w-[1180px] px-10 py-9">{children}</div>
        </main>
        <MissionBar />
      </div>
    </div>
  );
}
