#!/usr/bin/env node
/**
 * Licence audit of everything shipped inside the Mochi app: the runtime dependency closure of the packages the
 * main process and renderers bundle, plus Electron. Writes THIRD_PARTY_NOTICES.md and flags non-permissive licences.
 *   node tools/license-audit.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Packages bundled into the shipped app (main: zod, Anthropic SDK; renderers: React UI stack) and the runtime itself.
const ROOTS = ['electron', 'zod', '@anthropic-ai/sdk', 'react', 'react-dom', 'recharts', 'motion', 'zustand', 'lucide-react', 'clsx', 'tailwind-merge'];
const PERMISSIVE = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|CC0-1\.0|Unlicense|BlueOak-1\.0\.0|Python-2\.0)$/;

const seen = new Map();
function resolvePkg(name, fromDir) {
  for (let d = fromDir; ; d = dirname(d)) {
    const p = join(d, 'node_modules', name, 'package.json');
    if (existsSync(p)) return p;
    if (d === dirname(d)) return null;
  }
}
function visit(name, fromDir) {
  const p = resolvePkg(name, fromDir);
  if (!p) return;
  const pkg = JSON.parse(readFileSync(p, 'utf8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses?.map((l) => l.type).join(' OR ') || 'UNKNOWN');
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
  seen.set(key, { name: pkg.name, version: pkg.version, license, repo: repo.replace(/^git\+/, '').replace(/\.git$/, '') });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dirname(p));
}
for (const r of ROOTS) visit(r, join(root, 'apps', 'desktop'));

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
// "A OR B": at least one permissive option. "A AND B": every part must be permissive.
const ok = (lic) => lic.replace(/[()]/g, '').split(/\s+OR\s+/).some((alt) => alt.split(/\s+AND\s+/).every((l) => PERMISSIVE.test(l.trim())));
const flagged = rows.filter((r) => !ok(r.license));
const counts = rows.reduce((a, r) => ((a[r.license] = (a[r.license] ?? 0) + 1), a), {});
const md = [
  '# Third-party notices',
  '',
  'Mochi ships the following open-source software inside the application (runtime dependency closure, generated by `node tools/license-audit.mjs`). Electron additionally bundles Chromium and Node.js; their notices ship inside the app as `LICENSES.chromium.html` and `LICENSE`.',
  '',
  'The local language model is **not** shipped with Mochi. Ollama and Qwen3 are installed separately by the user (Ollama: MIT licence; Qwen3 models: Apache-2.0 per their model cards, verify before redistribution).',
  '',
  `Summary: ${rows.length} packages — ${Object.entries(counts).map(([l, n]) => `${l} ×${n}`).join(', ')}.`,
  flagged.length ? `\n**Needs review:** ${flagged.map((f) => `${f.name}@${f.version} (${f.license})`).join(', ')}\n` : '\nAll licences are permissive.\n',
  '| Package | Version | Licence | Source |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`),
  '',
].join('\n');
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`${rows.length} packages; licences: ${JSON.stringify(counts)}`);
console.log(flagged.length ? `NEEDS REVIEW: ${flagged.map((f) => `${f.name}@${f.version} (${f.license})`).join(', ')}` : 'all permissive');
